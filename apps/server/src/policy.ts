// CRYPTO_SPEC §6.4 のサーバー受理ポリシー(2026-08-02 追加)。
//
// これらは「チェーン有効性の合意規則」ではない: §6.1 のフィールド上限(合意規則)が
// 仕様適合エントリの正規化サイズを最大約 516 KiB に束縛するため、この受理ポリシーが
// 仕様適合エントリを拒否することはない(チェーン分裂を生まない)。値の引き上げは
// 過去チェーンの有効性に影響しない。

/** §6.4: 1 エントリの正規化バイト列(entry_bytes)の受理上限。 */
export const MAX_ENTRY_CANONICAL_BYTES = 1 * 1024 * 1024;

/** §6.4: チェーン全体のエントリ数の受理上限。 */
export const MAX_CHAIN_ENTRIES = 10_000;

/** §6.4: チェーン全体の正規化バイト列の累積受理上限。 */
export const MAX_CHAIN_TOTAL_CANONICAL_BYTES = 32 * 1024 * 1024;

/**
 * HTTP 境界の生ボディ上限(実装詳細。仕様は正規化バイト列基準のみを規定)。
 * JSON エスケープによる膨張(最悪 6 倍近く)を見込んで正規化上限より大きく取る。
 * 超過は JSON パースに入る前に素の 413 で拒否する(メモリ DoS の前段防御)。
 *
 * 8 MiB の根拠: 登録署名(CRYPTO_SPEC §5.1)の追加で 1 ラップのワイヤは
 * 約 500 バイトになり、件数上限(§12-8 の 10,000)ちょうどのラップ登録は
 * 約 5 MB に達する。件数超過の 422(dek-wraps-per-request)が transport 413 に
 * 覆われて到達不能にならないよう、最大件数のリクエストがスキーマ検査まで
 * 届く値に取る(ULID 長 user_id 前提。理論極値 = 1024 バイト user_id では
 * 従来どおり 413 が先に束縛しうる — AUTH_SPEC §12-8 の注記)。
 */
export const MAX_REQUEST_BODY_BYTES = 8 * 1024 * 1024;

// ---------------------------------------------------------------------------
// データプレーンの受理ポリシー(AUTH_SPEC §12-8。合意規則ではない — セルフ
// ホストでの引き上げは自由)。表示名の 256 文字上限は api-schema の Schema が
// 強制する(値と違い専用の検証層がないため)。
// ---------------------------------------------------------------------------

/** §12-8: 値の暗号文(ct || tag)の受理上限。 */
export const MAX_VALUE_CIPHERTEXT_BYTES = 64 * 1024;

/** §12-8: プロジェクトあたりのアクティブ環境数。 */
export const MAX_ACTIVE_ENVIRONMENTS = 100;

/** §12-8: プロジェクトあたりの環境行数(tombstone 込み。ID 焼却の資源保護)。 */
export const MAX_ENVIRONMENT_ROWS = 1_000;

/** §12-8: 環境あたりのアクティブ変数数。 */
export const MAX_ACTIVE_VARIABLES_PER_ENVIRONMENT = 1_000;

/** §12-8: 環境あたりの変数行数(tombstone 込み)。 */
export const MAX_VARIABLE_ROWS_PER_ENVIRONMENT = 5_000;

/** §12-8: 変数あたりのバージョン数。 */
export const MAX_VERSIONS_PER_VARIABLE = 1_000;

/** §12-8: プロジェクトの累積暗号文バイト(現在保存中の量。削除で解放される)。 */
export const MAX_PROJECT_CIPHERTEXT_TOTAL_BYTES = 1024 * 1024 * 1024;

/**
 * §12-8: 1 リクエストの DEK ラップ数。チェーン受理ポリシー(10,000 エントリ)が
 * 束縛するメンバー数上限以上に取り、初回登録の完全一致要件(§12-6)と両立させる。
 */
export const MAX_DEK_WRAPS_PER_REQUEST = 10_000;

/**
 * §12-8: プロジェクトあたりの DEK ラップ行数(現在保存中の量。環境削除・ラップ
 * 削除で解放される)。リクエスト単位の上限だけでは反復リクエストの累積が有界に
 * ならないため、現実的利用(メンバー × 環境 × エポック)の 3 桁上に置く。
 * 検査はラップ挿入の全経路(DEK 登録・環境作成)で行う。
 */
export const MAX_PROJECT_DEK_WRAP_ROWS = 1_000_000;

// ---------------------------------------------------------------------------
// ワークロードリースの受理ポリシー(AUTH_SPEC §14-3 / AUDIT_SPEC §3.5)。
// §12-8 と同じ性格 = 合意規則ではない(セルフホストでの引き上げは自由)。
// oidcToken の 16 KiB 上限は api-schema の Schema が強制する(表示名と同じ理由 —
// 専用の検証層を持たないため)。
// ---------------------------------------------------------------------------

/** §14-3: リースの固定窓の長さ(1 時間)。発行・拒否記録で共有する。 */
export const LEASE_WINDOW_MS = 60 * 60 * 1000;

/**
 * §14-3: 固定窓あたりのリース発行数(プロジェクト単位)。判定は**認可の後**に
 * 行う — 前に置くと未認可の呼び出し元にも 429 が返り、プロジェクトの存在が
 * 漏れる(§11-2)。認可後に置くことで、窓を消費できるのは「許可 issuer の
 * 有効署名 × チェーン上の lease_policy 一致」を満たす主体だけになる。
 */
export const MAX_LEASES_PER_WINDOW = 300;

/**
 * **影響半径の注記(pullfrog 指摘 — PR #65)**: 窓は `lease_windows` の 1 行を
 * プロジェクト(= DO)全体で共有するため、この 300 発/時は当該プロジェクトの
 * **全環境 × 全ワークロード同一性の合計**である。モノレポで prod / staging /
 * dev を 1 プロジェクトに置き、複数リポジトリの CI が引く構成では、1 つの
 * 活発な(あるいは暴走した)ジョブが窓を食い切ると同プロジェクトの CI 全体が
 * 最大 1 時間リースできない。存在秘匿には影響しない(認可を通らないと窓に
 * 到達しない)が、可用性ではノイジーネイバーになりうる。v1 は §14-3 の
 * 「プロジェクトあたり」の文言どおり単純な形を採る — 窓を環境 ID や
 * claims_digest 単位へ分割するのは仕様の粒度変更を伴うため申し送りとする
 * (セルフホストでの引き上げは §14-3 のとおり自由)。
 */

/**
 * AUDIT_SPEC §3.5: server.lease_denied の固定窓あたりの記録行数。
 * auth.login_failed と同じ規律(超過は不記録。プローブによる監査ログ肥大の遮断)。
 */
export const MAX_LEASE_DENIED_ROWS_PER_WINDOW = 100;

/** JSON の素朴なオブジェクト読み(それ以外の形は空オブジェクトへ潰す)。 */
function recordOf(value: unknown): Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value)
    ? (value as Record<string, unknown>)
    : {};
}

/** 変数集合の差(ファイル側にだけ / ストア側にだけある名前)。 */
function propertySetDivergence(
  fileNames: ReadonlySet<string>,
  expectedNames: ReadonlySet<string>,
): string[] {
  const missing = [...expectedNames].filter((name) => !fileNames.has(name));
  const extra = [...fileNames].filter((name) => !expectedNames.has(name));
  return [
    ...(missing.length === 0
      ? []
      : [
          `variables in the store but missing from the snapshot: ${missing.map(displayText).join(", ")}`,
        ]),
    ...(extra.length === 0
      ? []
      : [`variables in the snapshot but not in the store: ${extra.map(displayText).join(", ")}`]),
  ];
}

/** 共有変数の欄比較: 欄名のみ報告する(内容 — 特に description — は出さない)。 */
function propertyFieldDivergence(
  fileProperties: Record<string, unknown>,
  expected: SchemaSnapshot,
): string[] {
  const details: string[] = [];
  for (const [name, expectedProperty] of Object.entries(expected.properties)) {
    // own-property 参照(`toString` 等の正当な変数名が継承プロパティに解決される
    // 誤診断を防ぐ — floor.ts の floorRecordGet と同じ規律)
    if (!Object.hasOwn(fileProperties, name)) {
      continue;
    }
    const fileProperty = recordOf(fileProperties[name]);
    const differing = (["type", "format", "description"] as const).filter(
      (field) => fileProperty[field] !== expectedProperty[field],
    );
    if (differing.length > 0) {
      details.push(`variable ${displayText(name)}: field(s) differ: ${differing.join(", ")}`);
    }
  }
  return details;
}

/** required リストの差(対称差の変数名のみ)。 */
function requiredDivergence(fileRequired: unknown, expected: SchemaSnapshot): string[] {
  const fileSet = new Set(
    Array.isArray(fileRequired)
      ? fileRequired.filter((entry): entry is string => typeof entry === "string")
      : [],
  );
  const expectedSet = new Set(expected.required);
  const symmetricDiff = new Set([
    ...[...expectedSet].filter((name) => !fileSet.has(name)),
    ...[...fileSet].filter((name) => !expectedSet.has(name)),
  ]);
  return symmetricDiff.size === 0
    ? []
    : [`the required list differs for: ${[...symmetricDiff].map(displayText).join(", ")}`];
}

/**
 * 乖離の構造診断(判定はバイト一致 — 診断はどこが違うかの案内)。報告は
 * **変数名・欄名まで**: description の内容(ファイル側・ストア側とも)を
 * 端末レポートへ出さない(§2 の消費点規律 — レポートはログ・CI へ流れる)。
 */
function describeSnapshotDivergence(fileContent: string, expected: SchemaSnapshot): string[] {
  let parsed: unknown;
  try {
    parsed = JSON.parse(fileContent);
  } catch {
    return ["the committed snapshot is not valid JSON"];
  }
  if (typeof parsed !== "object" || parsed === null || Array.isArray(parsed)) {
    return ["the committed snapshot's top level is not an object"];
  }
  const record = parsed as Record<string, unknown>;
  const fileProperties = recordOf(record["properties"]);
  const details = [
    // 変数集合がたまたま一致する別環境のファイルは generic な整形差の文言に
    // 落ちて読めない — title(環境 ID を含む生成値)の不一致を名指しする
    // (ファイル側の title の**内容**は出さない: 攻撃者が書ける自由文字列)
    ...(record["title"] === expected.title
      ? []
      : [
          "the title does not match the generated form (the snapshot may have been generated for a different environment)",
        ]),
    ...propertySetDivergence(
      new Set(Object.keys(fileProperties)),
      new Set(Object.keys(expected.properties)),
    ),
    ...propertyFieldDivergence(fileProperties, expected),
    ...requiredDivergence(record["required"], expected),
  ];
  if (details.length === 0) {
    // バイト不一致だが構造の要点は一致 — 整形・枠付けヘッダ・並び順の差
    details.push(
      "the framing, formatting or ordering differs from the generated form (regenerate the file)",
    );
  }
  return details;
}

/**
 * Verifies a committed snapshot file against the snapshot regenerated from
 * the verified store, and fails loudly (exit 1) on any divergence (§1-6).
 * The comparison is an exact byte comparison of the deterministic generated
 * form; the divergence report names variables and fields only — never
 * description contents.
 */
export function schemaVerifySnapshotOp(
  input: SnapshotSourceInput & {
    /** 表示用のファイルパス(内容は fileContent — 読み込みは呼び出し側)。 */
    readonly filePath: string;
    readonly fileContent: string;
  },
): Effect.Effect<void, CliError, CliIo> {
  return Effect.gen(function* () {
    const io = yield* CliIo;
    const snapshot = yield* pullSnapshot(input);
    const expected = formatSchemaSnapshot(snapshot);
    if (input.fileContent === expected) {
      yield* io.log(
        `Snapshot ${displayText(input.filePath)} matches the store (environment ${displayText(input.environmentId)}, ${Object.keys(snapshot.properties).length} variables)`,
      );
      return;
    }
    const details = describeSnapshotDivergence(input.fileContent, snapshot);
    return yield* Effect.fail(
      cliError(
        `Snapshot ${displayText(input.filePath)} diverges from the store (environment ${displayText(input.environmentId)}):\n` +
          details.map((line) => `  - ${line}`).join("\n") +
          "\nThe store is the source of truth — regenerate the file with: maruhi schema export > <file>",
      ),
    );
  });
}
